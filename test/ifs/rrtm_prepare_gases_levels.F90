PROGRAM RRTM_PREPARE_GASES_LEVELS

USE PARKIND1, ONLY : JPIM, JPRB
USE PARRRTM, ONLY : JPINPX, JPXSEC
USE YOMHOOK, ONLY : LHOOK, DR_HOOK, JPHOOK
USE YOMLUN_ECRAD, ONLY : NULOUT

IMPLICIT NONE

INTEGER(KIND=JPIM), PARAMETER :: ILON=4, ILEV=6, ISTARTCOL=2, IENDCOL=3
INTEGER(KIND=JPIM) :: JK, JL, INLEV
REAL(KIND=JPRB) :: ZPH(ILON,ILEV+1), ZTH(ILON,ILEV+1), ZQ(ILON,ILEV)
REAL(KIND=JPHOOK) :: ZHOOK_HANDLE

#include "rrtm_prepare_gases.intfb.h"
#include "abor1.intfb.h"

IF (LHOOK) CALL DR_HOOK('RRTM_PREPARE_GASES_LEVELS',0,ZHOOK_HANDLE)

! Distinct columns and heights expose horizontal and vertical indexing errors.
DO JK=1,ILEV+1
  DO JL=1,ILON
    ZPH(JL,JK)=1000.0_JPRB*REAL(JK*JK+JL,KIND=JPRB)
    ZTH(JL,JK)=200.0_JPRB+REAL(JK*JK+JL,KIND=JPRB)
  ENDDO
ENDDO
ZQ(:,:)=0.001_JPRB

! Full atmosphere, lower-atmosphere slices, and the one-layer canopy path.
DO INLEV=ILEV,1,-1
  CALL CHECK_LEVELS(INLEV)
ENDDO

IF (LHOOK) CALL DR_HOOK('RRTM_PREPARE_GASES_LEVELS',1,ZHOOK_HANDLE)

CONTAINS

SUBROUTINE CHECK_LEVELS(KLEV)

IMPLICIT NONE

INTEGER(KIND=JPIM), INTENT(IN) :: KLEV
INTEGER(KIND=JPIM) :: ISTARTLEV, ILEVEL, JLEVEL, JCOL
INTEGER(KIND=JPIM) :: IREFLECT(ISTARTCOL:IENDCOL)
REAL(KIND=JPRB) :: ZCOLDRY(ISTARTCOL:IENDCOL,KLEV), ZWBRODL(ISTARTCOL:IENDCOL,KLEV)
REAL(KIND=JPRB) :: ZWKL(ISTARTCOL:IENDCOL,JPINPX,KLEV), ZWX(ISTARTCOL:IENDCOL,JPXSEC,KLEV)
REAL(KIND=JPRB) :: ZAVEL(ISTARTCOL:IENDCOL,KLEV), ZTAVEL(ISTARTCOL:IENDCOL,KLEV)
REAL(KIND=JPRB) :: ZZ(ISTARTCOL:IENDCOL,0:KLEV), ZTZ(ISTARTCOL:IENDCOL,0:KLEV)
REAL(KIND=JPRB) :: ZEXPECTED
REAL(KIND=JPHOOK) :: ZHOOK_HANDLE_LEVELS

IF (LHOOK) CALL DR_HOOK('RRTM_PREPARE_GASES_LEVELS:CHECK_LEVELS',0,ZHOOK_HANDLE_LEVELS)

! Keep exact-sized automatic arrays in a subroutine: ifx 2023.2 crashes on
! the original nested BLOCK version of this test when -init=snan is enabled.
ISTARTLEV=ILEV-KLEV+1
CALL RRTM_PREPARE_GASES(ISTARTCOL,IENDCOL,ILON,KLEV, &
 & ZPH(:,ISTARTLEV:ILEV+1),ZTH(:,ISTARTLEV:ILEV+1), &
 & ZQ(:,ISTARTLEV:ILEV),ZQ(:,ISTARTLEV:ILEV),ZQ(:,ISTARTLEV:ILEV), &
 & ZQ(:,ISTARTLEV:ILEV),ZQ(:,ISTARTLEV:ILEV),ZQ(:,ISTARTLEV:ILEV), &
 & ZQ(:,ISTARTLEV:ILEV),ZQ(:,ISTARTLEV:ILEV),ZQ(:,ISTARTLEV:ILEV), &
 & ZQ(:,ISTARTLEV:ILEV),ZCOLDRY,ZWBRODL,ZWKL,ZWX,ZAVEL,ZTAVEL,ZZ,ZTZ,IREFLECT)

DO JLEVEL=1,KLEV
  ILEVEL=ILEV-JLEVEL+1
  DO JCOL=ISTARTCOL,IENDCOL
    ! These analytic values are exactly representable in both precisions.
    ZEXPECTED=5.0_JPRB*REAL(ILEVEL*ILEVEL+(ILEVEL+1)*(ILEVEL+1)+2*JCOL,KIND=JPRB)
    CALL CHECK_VALUE(ZAVEL(JCOL,JLEVEL),ZEXPECTED,'layer pressure',KLEV,JCOL,JLEVEL)
    ZEXPECTED=200.0_JPRB+0.5_JPRB*REAL(ILEVEL*ILEVEL+(ILEVEL+1)*(ILEVEL+1)+2*JCOL,KIND=JPRB)
    CALL CHECK_VALUE(ZTAVEL(JCOL,JLEVEL),ZEXPECTED,'layer temperature',KLEV,JCOL,JLEVEL)
    CALL CHECK_VALUE(ZZ(JCOL,JLEVEL),ZPH(JCOL,ILEVEL)/100.0_JPRB,'interface pressure',KLEV,JCOL,JLEVEL)
    CALL CHECK_VALUE(ZTZ(JCOL,JLEVEL),ZTH(JCOL,ILEVEL),'interface temperature',KLEV,JCOL,JLEVEL)
    IF (ZCOLDRY(JCOL,JLEVEL) <= 0.0_JPRB) THEN
      WRITE(NULOUT,'(A,3(I0,1X),A,ES24.16)') &
       & 'Nonpositive dry column: nlev, column, RRTM level = ',KLEV,JCOL,JLEVEL,'value = ',ZCOLDRY(JCOL,JLEVEL)
      CALL ABOR1('Nonpositive RRTM dry column')
    ENDIF
  ENDDO
ENDDO

IF (LHOOK) CALL DR_HOOK('RRTM_PREPARE_GASES_LEVELS:CHECK_LEVELS',1,ZHOOK_HANDLE_LEVELS)

END SUBROUTINE CHECK_LEVELS

SUBROUTINE CHECK_VALUE(PACTUAL,PEXPECTED,CDQUANTITY,KLEV,KCOL,KLEVEL)

IMPLICIT NONE

REAL(KIND=JPRB), INTENT(IN) :: PACTUAL, PEXPECTED
CHARACTER(LEN=*), INTENT(IN) :: CDQUANTITY
INTEGER(KIND=JPIM), INTENT(IN) :: KLEV, KCOL, KLEVEL
REAL(KIND=JPHOOK) :: ZHOOK_HANDLE_VALUE

IF (LHOOK) CALL DR_HOOK('RRTM_PREPARE_GASES_LEVELS:CHECK_VALUE',0,ZHOOK_HANDLE_VALUE)

IF (PACTUAL /= PEXPECTED) THEN
  WRITE(NULOUT,'(3A,3(I0,1X))') 'Incorrect ',CDQUANTITY,': nlev, column, RRTM level = ',KLEV,KCOL,KLEVEL
  WRITE(NULOUT,'(A,ES24.16,A,ES24.16)') 'Actual = ',PACTUAL,', expected = ',PEXPECTED
  CALL ABOR1('Incorrect sliced RRTM gas preparation')
ENDIF

IF (LHOOK) CALL DR_HOOK('RRTM_PREPARE_GASES_LEVELS:CHECK_VALUE',1,ZHOOK_HANDLE_VALUE)

END SUBROUTINE CHECK_VALUE

END PROGRAM RRTM_PREPARE_GASES_LEVELS
