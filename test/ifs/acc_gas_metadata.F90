PROGRAM ACC_GAS_METADATA
  USE OPENACC, ONLY : ACC_ON_DEVICE, ACC_DEVICE_HOST
  USE PARKIND1, ONLY : JPIM, JPRB, JPRM
  USE RADIATION_GAS, ONLY : GAS_TYPE, IMASSMIXINGRATIO, IVOLUMEMIXINGRATIO
  USE RADIATION_GAS_CONSTANTS, ONLY : IH2O
  USE RADIATION_IO, ONLY : NULOUT, NULERR, RADIATION_ABORT
  IMPLICIT NONE

  INTEGER(KIND=JPIM), PARAMETER :: ICOL = 3, ILEV = 2
  TYPE(GAS_TYPE) :: YLGAS
  REAL(KIND=JPRM) :: ZINPUT(ICOL,ILEV)
  REAL(KIND=JPRB) :: ZSCALE
  INTEGER(KIND=JPIM) :: IPASS, IUNITS, IERROR, JL, JK

  CALL YLGAS%ALLOCATE(ICOL, ILEV)
  ZINPUT(:,:) = 0.125_JPRM
  !$ACC ENTER DATA COPYIN(YLGAS, ZINPUT)
  CALL YLGAS%CREATE_DEVICE()

  DO IPASS = 1,2
    IF (IPASS == 1) THEN
      IUNITS = IVOLUMEMIXINGRATIO
      ZSCALE = 0.5_JPRB
    ELSE
      IUNITS = IMASSMIXINGRATIO
      ZSCALE = 0.25_JPRB
    ENDIF
    ! JPRM input exercises the affected overload in both SP and DP libraries.
    CALL YLGAS%PUT(IH2O, IUNITS, ZINPUT, SCALE_FACTOR=ZSCALE, LACC=.TRUE.)
    !$ACC WAIT(1)
    !$ACC SERIAL DEFAULT(PRESENT) COPYOUT(IERROR) FIRSTPRIVATE(IUNITS, ZSCALE)
    IERROR = 0
    IF (ACC_ON_DEVICE(ACC_DEVICE_HOST)) IERROR = IERROR + 1
    IF (.NOT. YLGAS%IS_PRESENT(IH2O)) IERROR = IERROR + 1
    IF (YLGAS%IUNITS(IH2O) /= IUNITS) IERROR = IERROR + 1
    IF (YLGAS%SCALE_FACTOR(IH2O) /= ZSCALE) IERROR = IERROR + 1
    IF (YLGAS%IS_WELL_MIXED(IH2O)) IERROR = IERROR + 1
    IF (YLGAS%ICODE(1) /= IH2O) IERROR = IERROR + 1
    DO JK = 1,ILEV
      DO JL = 1,ICOL
        IF (YLGAS%MIXING_RATIO(JL,JK,IH2O) /= 0.125_JPRB) IERROR = IERROR + 1
      ENDDO
    ENDDO
    !$ACC END SERIAL
    IF (IERROR /= 0) THEN
      WRITE(NULERR,*) 'ACC_GAS_METADATA: pass, errors ', IPASS, IERROR
      CALL RADIATION_ABORT()
    ENDIF
  ENDDO

  CALL YLGAS%DELETE_DEVICE()
  !$ACC WAIT(1)
  !$ACC EXIT DATA DELETE(YLGAS, ZINPUT)
  CALL YLGAS%DEALLOCATE()
  WRITE(NULOUT,*) 'ACC_GAS_METADATA: device values and metadata agree'
END PROGRAM ACC_GAS_METADATA
